-- Migracion: Listas de precios multiples
-- Ejecutar en la base de datos NinOS
-- Espejo de la migracion EF AddPriceLists. Las tablas arrancan vacias: sin
-- listas creadas el sistema usa solo el precio original, igual que siempre.

CREATE TABLE IF NOT EXISTS price_list (
    id_price_list INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(500),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    is_principal BOOLEAN NOT NULL DEFAULT FALSE,
    sort_order INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Bases que ya tenian la tabla creada: agregar columnas sin recrearla.
ALTER TABLE price_list ADD COLUMN IF NOT EXISTS description VARCHAR(500);
ALTER TABLE price_list ADD COLUMN IF NOT EXISTS is_principal BOOLEAN NOT NULL DEFAULT FALSE;

CREATE UNIQUE INDEX IF NOT EXISTS IX_price_list_name ON price_list (name);

CREATE TABLE IF NOT EXISTS product_price (
    id_product_price INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_product INTEGER NOT NULL,
    id_price_list INTEGER NOT NULL,
    unit_price_usd NUMERIC(18,2) NOT NULL,
    CONSTRAINT FK_product_price_product_id_product FOREIGN KEY (id_product)
        REFERENCES product (id_product) ON DELETE CASCADE,
    CONSTRAINT FK_product_price_price_list_id_price_list FOREIGN KEY (id_price_list)
        REFERENCES price_list (id_price_list) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS IX_product_price_id_price_list ON product_price (id_price_list);
CREATE UNIQUE INDEX IF NOT EXISTS IX_product_price_id_product_id_price_list
    ON product_price (id_product, id_price_list);

ALTER TABLE note_detail ADD COLUMN IF NOT EXISTS id_price_list INTEGER;

CREATE INDEX IF NOT EXISTS IX_note_detail_id_price_list ON note_detail (id_price_list);

ALTER TABLE note_detail ADD CONSTRAINT FK_note_detail_price_list_id_price_list
    FOREIGN KEY (id_price_list) REFERENCES price_list (id_price_list) ON DELETE RESTRICT;
